def render_banner(version: str, cwd: str) -> str:
    """拼装启动横幅：ASCII 图案 + 应用名与版本号 + 当前工作目录 + 就绪提示行。"""
    return (
        f"{BANNER.rstrip()}\n"
        f"\n"
        f"  PotatoCode v{version}\n"
        f"  cwd: {cwd}\n"
        f"\n"
        f"  Ready. 输入消息开始对话（Enter 发送 · Alt+Enter 换行 · /exit 退出）\n"
    )
